#!/usr/bin/env node
/**
 * End-to-end benchmark for the real plugin.
 *
 * It calls `tool.execute` from ../../lib/index.mjs (no reimplementation of the
 * scanner). Two packs are used:
 *
 *  1. the shipped rules/construction-doc-check.yaml, for the generic
 *     zero-byte (CD-041) and stale-version (CD-040) rules;
 *  2. a bench-generated exact-filename pack, for "the six public documents are
 *     present under their upstream names". The generated pack is data passed
 *     through the plugin's supported `rulePackFile` argument; the plugin still
 *     does all the scanning and matching.
 *
 * The Chinese document-type rules are NOT scored: UFGS specification sections
 * are not Chinese project records. See adapter.mjs and README.md.
 *
 * Usage:
 *   node bench/public-construction/evaluate.mjs
 *   node bench/public-construction/evaluate.mjs --keep           keep the temp dirs
 *   node bench/public-construction/evaluate.mjs --from-summary   re-render RESULTS.md only
 */
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { join, resolve, sep } from 'node:path'
import { performance } from 'node:perf_hooks'
import * as plugin from '../../lib/index.mjs'
import {
  BENCH_DIR,
  MAPPED_RULE_IDS,
  SEMANTIC_MAPPING,
  TMP_DIR,
  createRunRoot,
  duplicateDocument,
  exactFilenamePattern,
  loadSources,
  materializeProject,
  projectPathOf,
  removeDocument,
  sha256,
  verifyData,
  zeroDocument,
} from './adapter.mjs'

const here = BENCH_DIR
const keep = process.argv.includes('--keep')
const sources = await loadSources()
const documents = sources.documents
const docsById = new Map(documents.map((doc) => [doc.id, doc]))

if (MAPPED_RULE_IDS.length !== 0) {
  throw new Error(
    `This bench was written for zero semantic mappings, found: ${MAPPED_RULE_IDS.join(', ')}. ` +
      `Re-read adapter.mjs before scoring the Chinese rules.`,
  )
}

const CASES = [
  { id: 'clean-flat', layout: 'flat' },
  { id: 'clean-nested', layout: 'nested' },
  { id: 'missing-one', layout: 'flat', remove: ['UFGS-01-45-00'] },
  { id: 'missing-two-nested', layout: 'nested', remove: ['UFGS-01-33-00', 'UFGS-01-74-19'] },
  { id: 'zero-one', layout: 'flat', zero: ['UFGS-01-78-00'] },
  { id: 'zero-two-nested', layout: 'nested', zero: ['UFGS-01-32-01-00-10', 'UFGS-01-35-26'] },
  {
    id: 'stale-paren',
    layout: 'flat',
    duplicate: [{ docId: 'UFGS-01-33-00', alias: 'UFGS 01 33 00 (1).pdf' }],
  },
  {
    id: 'stale-v2',
    layout: 'nested',
    duplicate: [{ docId: 'UFGS-01-78-00', alias: 'UFGS 01 78 00 V2.pdf' }],
  },
  {
    id: 'mixed',
    layout: 'nested',
    remove: ['UFGS-01-45-00'],
    zero: ['UFGS-01-74-19'],
    duplicate: [{ docId: 'UFGS-01-35-26', alias: 'UFGS 01 35 26 (2).pdf' }],
  },
]

for (const spec of CASES) {
  const referenced = [
    ...(spec.remove ?? []),
    ...(spec.zero ?? []),
    ...(spec.duplicate ?? []).map((item) => item.docId),
  ]
  for (const docId of referenced) {
    if (!docsById.has(docId)) throw new Error(`case ${spec.id}: unknown document id ${docId}`)
  }
}

const presenceRules = documents.map((doc, index) => ({
  ruleId: `PB-${String(index + 1).padStart(3, '0')}`,
  doc,
}))
const presenceDocByRule = new Map(presenceRules.map((item) => [item.ruleId, item.doc.id]))

/** @param {string} value */
function yamlScalar(value) {
  if (String(value).includes("'")) throw new Error(`YAML fixture cannot single-quote: ${value}`)
  return `'${String(value)}'`
}

function buildPresencePack() {
  const lines = [
    '# Generated by evaluate.mjs. Bench fixture, not a normative rule pack.',
    '# One rule per public document; exact anchored basename, any folder.',
    'version: "public-ufgs-exact-filenames-2026-11-10"',
    'as_of: "2026-11-10"',
    'scan:',
    '  maxDepth: 6',
    "  skipDirs: ['.git', 'node_modules', '__MACOSX']",
    '  emptyFileBytes: 0',
    'rules:',
  ]
  for (const { ruleId, doc } of presenceRules) {
    lines.push(`  - id: ${ruleId}`)
    lines.push(`    title: ${yamlScalar(`Exact filename: ${doc.filename}`)}`)
    lines.push('    category: public-document-presence')
    lines.push('    severity: error')
    lines.push('    patterns:')
    lines.push(`      - ${yamlScalar(exactFilenamePattern(doc.filename))}`)
    lines.push('    basis:')
    lines.push('      document: Bench public-document manifest')
    lines.push(`      number: ${yamlScalar(`UFGS ${doc.section}`)}`)
    lines.push('      clause: exact filename presence')
    lines.push('      excerpt: Bench-only requirement derived from the downloaded public document list; not a normative citation.')
    lines.push('      kind: institutional-configuration')
    lines.push(`      source: ${doc.sourcePage}`)
  }
  return lines.join('\n') + '\n'
}

/** @param {any[]} left @param {any[]} right */
function sameSet(left, right) {
  const a = [...new Set(left)].sort()
  const b = [...new Set(right)].sort()
  return a.length === b.length && a.every((value, index) => value === b[index])
}

/** @param {string} message */
function staleBaseFromMessage(message) {
  const match = /^「(.*?)」在归档中有 \d+ 份/iu.exec(message)
  return match === null ? null : match[1]
}

/** @param {number|null} value */
function round(value) {
  return value === null ? null : Math.round(value * 10000) / 10000
}

/** @param {number} tp @param {number} fp @param {number} fn @param {number} tn */
function metrics(tp, fp, fn, tn) {
  const precision = tp + fp === 0 ? null : tp / (tp + fp)
  const recall = tp + fn === 0 ? null : tp / (tp + fn)
  const f1 =
    precision === null || recall === null || precision + recall === 0
      ? null
      : (2 * precision * recall) / (precision + recall)
  return {
    tp,
    fp,
    fn,
    tn,
    precision: round(precision),
    recall: round(recall),
    f1: round(f1),
    support: { positive: tp + fn, negative: tn + fp },
  }
}

async function main() {
  const verification = await verifyData(sources)
  if (!verification.ok) {
    const details = verification.checked
      .filter((item) => !item.ok)
      .map((item) => `  - ${item.filename}: ${item.reason}`)
      .join('\n')
    throw new Error(
      `public corpus is not available or does not match sources.json:\n${details}\n` +
        `Run: node bench/public-construction/fetch.mjs`,
    )
  }

  const registered = []
  const ctx = {
    tools: {
      register(tool) {
        registered.push(tool)
        return () => {}
      },
    },
  }
  plugin.apply(ctx, plugin.Config({}))
  const tool = registered.find((item) => item.name === plugin.TOOL_NAME)
  if (tool === undefined) throw new Error(`tool not registered: ${plugin.TOOL_NAME}`)
  const signal = new AbortController().signal

  const runRoot = await createRunRoot()
  const presencePackPath = join(runRoot, 'exact-filenames.yaml')
  await writeFile(presencePackPath, buildPresencePack())

  const pluginFile = resolve(here, '../../lib/index.mjs')
  const shippedPackFile = resolve(here, '../../rules/construction-doc-check.yaml')
  const pluginBytes = await readFile(pluginFile)
  const shippedPackBytes = await readFile(shippedPackFile)

  const results = []
  for (const spec of CASES) {
    const project = await materializeProject({
      runRoot,
      caseId: spec.id,
      documents,
      layout: spec.layout,
    })

    for (const docId of spec.remove ?? []) await removeDocument(project, docId)
    for (const docId of spec.zero ?? []) await zeroDocument(project, docId)
    const duplicates = []
    for (const item of spec.duplicate ?? []) {
      duplicates.push({ docId: item.docId, ...(await duplicateDocument(project, item.docId, item.alias)) })
    }

    // Labels come from the construction, never from the plugin's output.
    const expected = {
      presenceMissingDocIds: [...(spec.remove ?? [])].sort(),
      zeroBytePaths: (spec.zero ?? []).map((docId) => projectPathOf(docsById.get(docId), spec.layout)).sort(),
      staleVersionBases: duplicates.map((item) => item.base).sort(),
    }

    // Assert the injected state before asking the plugin about it.
    for (const docId of spec.remove ?? []) {
      const path = project.files.find((item) => item.docId === docId).absolute
      await stat(path).then(
        () => {
          throw new Error(`${spec.id}: ${docId} was not removed`)
        },
        () => {},
      )
    }
    for (const docId of spec.zero ?? []) {
      const path = project.files.find((item) => item.docId === docId).absolute
      const info = await stat(path)
      if (info.size !== 0) throw new Error(`${spec.id}: ${docId} is ${info.size} bytes, expected 0`)
    }
    for (const duplicate of duplicates) {
      const info = await stat(join(project.dir, duplicate.path))
      const original = docsById.get(duplicate.docId)
      if (info.size !== original.bytes) throw new Error(`${spec.id}: duplicate ${duplicate.path} has wrong size`)
    }

    const startedChinese = performance.now()
    const chinese = await tool.execute({ dir: project.dir }, { signal })
    const chineseMs = performance.now() - startedChinese
    const chineseFindings = JSON.parse(chinese.resultJson).findings

    const startedPresence = performance.now()
    const presence = await tool.execute(
      { dir: project.dir, rulePackFile: presencePackPath },
      { signal },
    )
    const presenceMs = performance.now() - startedPresence
    const presenceFindings = JSON.parse(presence.resultJson).findings

    if (chinese.plugin !== plugin.name || presence.plugin !== plugin.name) {
      throw new Error(`${spec.id}: unexpected plugin identity in tool output`)
    }

    const zeroObserved = chineseFindings
      .filter((finding) => finding.ruleId === 'CD-041')
      .flatMap((finding) => finding.evidence)
      .sort()
    const staleObserved = chineseFindings
      .filter((finding) => finding.ruleId === 'CD-040')
      .map((finding) => staleBaseFromMessage(finding.message))
      .filter((value) => value !== null)
      .sort()
    const presenceMissingRuleIds = presenceFindings
      .filter((finding) => finding.message.includes('没有找到'))
      .map((finding) => finding.ruleId)
      .sort()
    const presenceMissingDocIds = presenceMissingRuleIds
      .map((ruleId) => presenceDocByRule.get(ruleId))
      .filter((value) => value !== undefined)
      .sort()
    const headerFindings = chineseFindings.filter((finding) => finding.ruleId === 'CD-042')
    const chineseMissingRuleIds = chineseFindings
      .filter((finding) => finding.message.includes('没有找到'))
      .map((finding) => finding.ruleId)
      .sort()

    const exact = {
      presence: sameSet(presenceMissingDocIds, expected.presenceMissingDocIds),
      zeroByte: sameSet(zeroObserved, expected.zeroBytePaths),
      staleVersion: sameSet(staleObserved, expected.staleVersionBases),
    }
    const flagged = {
      presence: presenceMissingDocIds.length > 0,
      zeroByte: zeroObserved.length > 0,
      staleVersion: staleObserved.length > 0,
    }

    results.push({
      id: spec.id,
      layout: spec.layout,
      label: {
        presenceMissingDocIds: expected.presenceMissingDocIds,
        zeroBytePaths: expected.zeroBytePaths,
        staleVersionBases: expected.staleVersionBases,
      },
      observed: {
        presenceMissingDocIds,
        zeroBytePaths: zeroObserved,
        staleVersionBases: staleObserved,
        headerMismatchPaths: headerFindings.flatMap((finding) => finding.evidence).sort(),
      },
      exact,
      flagged,
      pass: Object.values(exact).every(Boolean),
      unscored: {
        chineseMissingRuleIds,
        chineseMissingCount: chineseMissingRuleIds.length,
        headerMismatchCount: headerFindings.length,
        note: 'Chinese document-type rules and CD-042 are not scored in this public-corpus bench.',
      },
      plugin: {
        packVersion: chinese.packVersion,
        filesScanned: chinese.summary.filesScanned,
        dirsScanned: chinese.summary.dirsScanned,
        summary: chinese.summary,
        presenceFilesScanned: presence.summary.filesScanned,
      },
      durationMs: Math.round(chineseMs + presenceMs),
    })
  }

  const checkDefinitions = {
    presence: {
      description:
        'Every required public document is present under its exact upstream filename (bench-generated pack, run by the real plugin).',
      rulePack: 'bench-generated exact-filename pack (rule ids PB-001…PB-006)',
      expectedKey: 'presenceMissingDocIds',
    },
    zeroByte: {
      description: 'Every injected zero-byte file is reported by CD-041.',
      rulePack: 'shipped rules/construction-doc-check.yaml',
      expectedKey: 'zeroBytePaths',
    },
    staleVersion: {
      description: 'Every injected revision-marked duplicate is reported by CD-040.',
      rulePack: 'shipped rules/construction-doc-check.yaml',
      expectedKey: 'staleVersionBases',
    },
  }

  const checks = {}
  for (const [name, definition] of Object.entries(checkDefinitions)) {
    let tp = 0
    let fp = 0
    let fn = 0
    let tn = 0
    for (const result of results) {
      const expectedPositive = result.label[definition.expectedKey].length > 0
      const predictedPositive = result.flagged[name]
      if (expectedPositive) {
        if (result.exact[name]) tp++
        else fn++
      } else if (predictedPositive) {
        fp++
      } else {
        tn++
      }
    }
    checks[name] = { ...definition, ...metrics(tp, fp, fn, tn) }
  }

  const contentScan = await tool.execute({ dir: join(here, '.data'), content: true }, { signal: new AbortController().signal })
  const contentStats = contentScan.content
  if (contentStats === undefined || contentStats.scanned !== documents.length || contentStats.withText !== documents.length) {
    throw new Error(`content scan: expected ${documents.length} text-layer PDFs, got ${JSON.stringify(contentStats)}`)
  }

  const passed = results.filter((result) => result.pass).length
  const generatedAt = new Date().toISOString()
  const summary = {
    benchmark: 'public-construction',
    generatedAt,
    status: passed === results.length ? 'pass' : 'fail',
    plugin: {
      name: plugin.name,
      version: JSON.parse(await readFile(resolve(here, '../../package.json'), 'utf8')).version,
      tool: plugin.TOOL_NAME,
      entry: '../../lib/index.mjs',
      entrySha256: sha256(pluginBytes),
      shippedPack: '../../rules/construction-doc-check.yaml',
      shippedPackSha256: sha256(shippedPackBytes),
      shippedPackVersion: results[0]?.plugin.packVersion ?? null,
    },
    contentScan: contentStats,
    corpus: {
      id: sources.corpus.id,
      title: sources.corpus.title,
      publisher: sources.corpus.publisher,
      documentKind: sources.corpus.documentKind,
      retrievedAt: sources.corpus.retrievedAt,
      license: sources.corpus.license,
      documents: documents.map((doc) => ({
        id: doc.id,
        section: doc.section,
        title: doc.title,
        filename: doc.filename,
        url: doc.url,
        sourcePage: doc.sourcePage,
        bytes: doc.bytes,
        sha256: doc.sha256,
      })),
    },
    semanticMapping: {
      mappedRuleIds: MAPPED_RULE_IDS,
      entries: SEMANTIC_MAPPING,
      note: 'No Chinese document-type rule is mapped. The generic rules CD-040/041 are scored; CD-042 is observed but not scored.',
    },
    method: {
      cases: CASES.length,
      labelsFrom: 'case construction, before the plugin runs',
      presenceRulePack: 'generated in the temp run directory from sources.json; passed to the real tool via rulePackFile',
      zeroByteRule: 'CD-041 from the shipped pack',
      staleVersionRule: 'CD-040 from the shipped pack',
      headerRule: 'CD-042 observed, not scored',
      scoring: 'case-level exact-set match; a check is correct only when the full expected and observed sets are equal',
    },
    checks,
    cases: results,
    totals: {
      cases: results.length,
      passed,
      failed: results.length - passed,
      checkInstances: results.length * Object.keys(checkDefinitions).length,
    },
    environment: {
      node: process.version,
      platform: process.platform,
      arch: process.arch,
      tempDirKept: keep ? '.tmp/run-*' : null,
    },
    limitations: [
      'The corpus is six UFGS specification sections, not a project archive. It contains no Chinese completion/acceptance records, logs, plans, or test reports.',
      'The Chinese rule pack therefore reports its 12 document types as missing on every case. Those findings are recorded as unscored, not counted as false positives.',
      'Presence scoring uses a bench-generated exact-filename pack, not the Chinese patterns. It tests scan/path matching, not Chinese form completeness.',
      'The adapter performs no semantic renaming: no UFGS section is treated as a 竣工验收记录, 监理日志, 检验批, 专项施工方案, or 应急预案.',
      'CD-042 (container header) is observed but not scored. It fires on zero-byte .pdf files as a side effect of CD-041 cases.',
      'One snapshot is pinned by URL + size + SHA-256. Upstream WBDG files can be replaced; fetch.mjs fails rather than silently measuring a changed corpus.',
      'Case-level P/R has a small denominator (9 cases). It is a regression harness for this plugin, not an estimate of field accuracy.',
      'No document content is parsed. A document merely being present, non-empty, and uniquely named is not evidence that its content is valid.',
    ],
  }

  await mkdir(here, { recursive: true })
  await writeFile(join(here, 'summary.json'), JSON.stringify(summary, null, 2) + '\n')
  await writeFile(join(here, 'RESULTS.md'), renderResults(summary))
  printSummary(summary, runRoot)

  if (!keep) {
    const target = resolve(runRoot)
    const base = resolve(TMP_DIR)
    if (!target.startsWith(base + sep)) throw new Error(`refusing to remove ${target}: outside ${base}`)
    await rm(target, { recursive: true, force: true })
  }
  if (summary.status !== 'pass') process.exitCode = 1
}

/** @param {any} summary @param {string} runRoot */
function printSummary(summary, runRoot) {
  console.log(`plugin: ${summary.plugin.name}@${summary.plugin.version} (${summary.plugin.shippedPackVersion})`)
  console.log(`corpus: ${summary.corpus.documents.length} public PDFs, ${summary.corpus.license.status}`)
  console.log(`cases: ${summary.totals.cases}, passed: ${summary.totals.passed}, failed: ${summary.totals.failed}`)
  for (const [name, check] of Object.entries(summary.checks)) {
    console.log(
      `${name.padEnd(12)} TP=${check.tp} FP=${check.fp} FN=${check.fn} TN=${check.tn} ` +
        `P=${check.precision ?? 'n/a'} R=${check.recall ?? 'n/a'} F1=${check.f1 ?? 'n/a'}`,
    )
  }
  if (summary.environment.tempDirKept !== null) console.log(`temp kept: ${runRoot}`)
  console.log(`wrote: ${join(here, 'summary.json')}`)
  console.log(`wrote: ${join(here, 'RESULTS.md')}`)
}

/** @param {any} summary */
function renderResults(summary) {
  const lines = []
  lines.push('# Public-construction end-to-end benchmark — results')
  lines.push('')
  lines.push(`Generated by \`node bench/public-construction/evaluate.mjs\` at ${summary.generatedAt}.`)
  lines.push('')
  lines.push('This file is rendered from `summary.json`; edit the generator, not this report.')
  lines.push('')
  lines.push(`**Status: ${summary.status.toUpperCase()}** — ${summary.totals.passed}/${summary.totals.cases} cases passed.`)
  lines.push('')
  lines.push('## What was run')
  lines.push('')
  lines.push('```sh')
  lines.push('node bench/public-construction/fetch.mjs')
  lines.push('node bench/public-construction/evaluate.mjs')
  lines.push('```')
  lines.push('')
  lines.push('The benchmark imports the built plugin at `../../lib/index.mjs`, registers `construction_doc_check` through `plugin.apply()`, and calls `tool.execute()` on temporary directories. No scanner logic is reimplemented.')
  lines.push('')
  lines.push('## Corpus and license')
  lines.push('')
  lines.push(`- Corpus: ${summary.corpus.title}`)
  lines.push(`- Publisher: ${summary.corpus.publisher}`)
  lines.push(`- Retrieved: ${summary.corpus.retrievedAt}`)
  lines.push(`- License status: **${summary.corpus.license.status}**`)
  lines.push(`- ${summary.corpus.license.summary}`)
  lines.push('')
  lines.push('| Section | Title | Bytes | Source |')
  lines.push('| --- | --- | ---: | --- |')
  for (const doc of summary.corpus.documents) {
    lines.push(`| ${doc.section} | ${doc.title} | ${doc.bytes} | [PDF](${doc.url}) · [page](${doc.sourcePage}) |`)
  }
  lines.push('')
  lines.push('The PDFs are gitignored (`bench/public-construction/.data/`); `fetch.mjs` re-downloads and verifies size + SHA-256.')
  lines.push('')
  lines.push('## Why there is no Chinese-form P/R')
  lines.push('')
  lines.push('UFGS sections are guide specifications. They are not filled 竣工验收记录, 竣工报告, 保修书, 检验批, 隐蔽工程验收记录, 分部工程验收记录, 材料复试报告, 监理日志, 施工日志, 危大专项方案, 危大验收记录, or 应急预案. The adapter therefore maps **none** of the Chinese document-type rules (`mappedRuleIds: []`) and does not rename PDFs into Chinese forms.')
  lines.push('')
  lines.push('The shipped pack consequently reports 12 missing Chinese document types in every case. Those findings are **unscored**; counting them as false positives would measure the corpus choice, not the plugin.')
  lines.push('')
  lines.push('## Scored checks')
  lines.push('')
  lines.push('| Check | Rule / pack | TP | FP | FN | TN | Precision | Recall | F1 |')
  lines.push('| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |')
  for (const [name, check] of Object.entries(summary.checks)) {
    lines.push(
      `| ${name} | ${check.rulePack} | ${check.tp} | ${check.fp} | ${check.fn} | ${check.tn} | ` +
        `${check.precision ?? 'n/a'} | ${check.recall ?? 'n/a'} | ${check.f1 ?? 'n/a'} |`,
    )
  }
  lines.push('')
  lines.push(`Scoring: ${summary.method.scoring}. Support per check: ` +
    Object.entries(summary.checks)
      .map(([name, check]) => `${name} ${check.support.positive} positive / ${check.support.negative} negative`)
      .join('; ') + '.')
  lines.push('')
  lines.push('## Cases')
  lines.push('')
  lines.push('| Case | Layout | Injected label | Presence | Zero-byte | Stale version | Result |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- |')
  for (const item of summary.cases) {
    const label = [
      item.label.presenceMissingDocIds.length > 0 ? `missing ${item.label.presenceMissingDocIds.join(', ')}` : '',
      item.label.zeroBytePaths.length > 0 ? `zero ${item.label.zeroBytePaths.join(', ')}` : '',
      item.label.staleVersionBases.length > 0 ? `stale ${item.label.staleVersionBases.join(', ')}` : '',
    ].filter(Boolean).join('; ') || 'clean'
    const cell = (name) => {
      const expectedKey = summary.checks[name].expectedKey
      const positive = item.label[expectedKey].length > 0
      const predicted = item.flagged[name]
      if (positive && predicted && item.exact[name]) return 'hit'
      if (positive) return '**MISS**'
      if (predicted) return '**FP**'
      return 'clean'
    }
    lines.push(`| ${item.id} | ${item.layout} | ${label} | ${cell('presence')} | ${cell('zeroByte')} | ${cell('staleVersion')} | ${item.pass ? 'pass' : '**fail**'} |`)
  }
  lines.push('')
  lines.push('## Observed but unscored')
  lines.push('')
  lines.push('| Case | Chinese missing types | CD-042 header findings |')
  lines.push('| --- | ---: | ---: |')
  for (const item of summary.cases) {
    lines.push(`| ${item.id} | ${item.unscored.chineseMissingCount} | ${item.unscored.headerMismatchCount} |`)
  }
  lines.push('')
  lines.push('CD-042 fires on zero-byte PDFs because their header is not `%PDF-`. It is a legitimate generic finding, but it is outside the three checks specified for this bench and is not scored.')
  lines.push('')
  lines.push('## Limitations')
  lines.push('')
  for (const limitation of summary.limitations) lines.push(`- ${limitation}`)
  lines.push('')
  return lines.join('\n')
}

